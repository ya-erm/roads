/**
 * Первый рейс маршрута, который ещё не возит пассажиров (новая линия или все машины проданы и куплена новая).
 *
 * Пассажиры на станции появляются, как только проложен маршрут (`Game.paxRoutes`), но копятся лишь до предела
 * станции без машин (`Game.stationCap`). Автобус же сажает всех, кто ждёт, в момент прибытия — у новой машины это
 * миг покупки — и при условии «авто» пассажиров не ждёт: раньше первый рейс уходил пустым, а пассажиры,
 * пришедшие за эти секунды, оставались ждать следующего круга.
 *
 * Теперь при условии «авто» первый рейс немного ждёт на первой станции, сажая подходящих: пока не займёт
 * половину мест или не выйдет предел ожидания. Подарка нет — сажает только тех, кто подошёл за это время,
 * с обычной скоростью появления пассажиров. Если до предела никто не успеет подойти (рядом нет жителей
 * или они едут другими маршрутами), ждать незачем — едет сразу. Условие «не ждать» — сразу в путь,
 * «полная загрузка» — до полной, как обычно.
 */
export const FIRST_RUN = {
  /** Дольше первый рейс не ждёт, секунд. */
  maxWait: 20,
  /** Занял столько мест от вместимости — едет, не дожидаясь предела. */
  fill: 0.5,
};

/**
 * Ждать ли первому рейсу ещё: waited — сколько секунд уже ждёт на первой станции, load и capacity — пассажиров
 * в салоне и мест, rate — сколько пассажиров в секунду появляется здесь до других остановок маршрута.
 */
export function firstRunWaits(waited: number, load: number, capacity: number, rate: number): boolean {
  if (capacity <= 0 || load >= capacity * FIRST_RUN.fill) return false;
  const left = FIRST_RUN.maxWait - waited;
  // До предела не подойдёт ни один пассажир — ждать незачем.
  return left > 0 && rate * left >= 1;
}
