/**
 * Модернизация в авто-парке: вышла модель новее — авто-парк меняет ею машины линии по одной (Game.updateAutoRenew).
 * Здесь — какой шаг сделать сейчас; деньги, замену на месте и продажу делает игра.
 */

/** Пауза между шагами модернизации одной линии, секунд игры: машины меняются по одной, деньги тратятся постепенно. */
export const RENEW_GAP = 20;

/** Машина линии старой модели, которую есть на что заменить. */
export interface RenewCar {
  id: number;
  /** Вместимость сейчас и после замены (у поезда — с тем же числом вагонов). */
  capacity: number;
  next: number;
  /** Свободна: стоит на станции (не в пути и не на заезде к посту) — меняется, не мешая линии. Продать можно и едущую. */
  free: boolean;
  /** Сколько везёт. */
  load: number;
}

export interface RenewInput {
  old: RenewCar[];
  /**
   * Запас вместимости, набранный модернизацией: новые больше старых. Набралось на целую старую машину —
   * её не меняют, а продают: машин нужно меньше, вместимость линии не меньше, чем была до модернизации.
   */
  spare: number;
  /** Машин на линии и минимум авто-парка: ниже минимума не продаёт. */
  count: number;
  min: number;
  /** Свободной пустой машины, которую можно продать, давно нет — продаёт и не пустую (её груз пропадёт). */
  waited: boolean;
}

export type RenewStep = { kind: 'replace'; id: number } | { kind: 'sell'; id: number } | null;

/**
 * Следующий шаг модернизации. Запас вместимости покрывает старую машину — продать самую незагруженную (лучше
 * стоящую на станции), как продаёт лишние авто-парк: пустую, хоть и едущую порожняком, а ждали долго — любую;
 * не пустой — ждать. Иначе — заменить на месте свободную: самую незагруженную из стоящих на станции (при равной —
 * первую по номеру); свободных нет — null: ждать, пока какая-нибудь встанет на станцию.
 */
export function renewStep({ old, spare, count, min, waited }: RenewInput): RenewStep {
  const order = (a: RenewCar, b: RenewCar) => a.load - b.load || Number(b.free) - Number(a.free) || a.id - b.id;
  const spareCar = [...old].sort(order)[0];
  if (spareCar && spare >= spareCar.capacity && count > min) return spareCar.load === 0 || waited ? { kind: 'sell', id: spareCar.id } : null;
  const car = old.filter((c) => c.free).sort(order)[0];
  return car ? { kind: 'replace', id: car.id } : null;
}
